-- ============ КРОК 1: бекфіл ============
update public.exercises e
set muscle_group = m.g
from (values
  -- ноги
  ('болгарські випади',            'ноги'),
  ('гуд морнінг в гаку',           'ноги'),
  ('жим ногами',                   'ноги'),
  ('зведення',                     'ноги'),   -- тренажер зведення ніг; якщо це «метелик» на груди — виправ
  ('згинання ніг назад',           'ноги'),
  ('присяд в гаку',                'ноги'),
  ('присяд сумо з гирею',          'ноги'),
  ('розведення',                   'ноги'),   -- тренажер розведення ніг
  ('розгинання',                   'ноги'),   -- розгинання ніг сидячи
  ('румунська в гаку',             'ноги'),
  ('румунська тяга',               'ноги'),
  ('сідничний мостик',             'ноги'),
  ('сідничний мостик (лавка)',     'ноги'),
  ('махи назад',                   'ноги'),   -- відведення ноги назад (сідниці); якщо це задня дельта — 'плечі'
  ('махи назад (тренажер)',        'ноги'),
  -- спина
  ('вертикальна тяга',             'спина'),
  ('горизонтальна тяга',           'спина'),
  ('пуловер',                      'спина'),
  ('тяга верхнього блоку',         'спина'),
  ('тяга горизонтального блоку',   'спина'),
  ('тяга штанги знизу до себе',    'спина'),
  -- груди
  ('жим від грудей',               'груди'),
  -- плечі
  ('жим гантелей сидячи',          'плечі'),
  ('канат до вух',                 'плечі'),  -- face pull: задня дельта
  ('махи',                         'плечі'),  -- махи гантелями в сторони
  -- руки
  ('згинання на біцепс молотки',   'руки'),
  ('тріцепс',                      'руки')
) as m(n, g)
where lower(trim(e.name)) = m.n
  and e.muscle_group is null;

-- ============ КРОК 2: перевірка — має бути порожньо ============
select id, name
from public.exercises
where muscle_group is null
order by name;

